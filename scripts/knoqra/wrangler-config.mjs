// Builds the self-host wrangler configs from the top-level blocks of the base wrangler.jsonc files
// and the saved settings. Pure: no file or network access.
import { API_WORKER, connectorsOf, originsOf, SetupError, WEB_WORKER } from './settings.mjs';

/** Workers Rate Limiting bindings (apps/api/src/lib/rate-limit.ts). Ids are unique per account. */
export const RATE_LIMITS = [
  { name: 'RL_AUTH', namespace_id: '1001', simple: { limit: 10, period: 60 } },
  { name: 'RL_DIAL', namespace_id: '1002', simple: { limit: 10, period: 60 } },
  { name: 'RL_VOICE_TOKEN', namespace_id: '1003', simple: { limit: 20, period: 60 } },
  { name: 'RL_MESSAGE_SEND', namespace_id: '1004', simple: { limit: 30, period: 60 } },
];

export const CONFIG_HEADER = [
  '// Generated by `pnpm knoqra deploy` from wrangler.jsonc and .env.selfhost. Do not commit it and',
  '// do not edit it by hand: change the settings and run `pnpm knoqra deploy config` again.',
  '',
].join('\n');

/** A self-hosted deployment always runs the selfhost edition, so the license check stays on. */
const EDITION = 'selfhost';

/** The base config without its `env` blocks and without fields this generator always sets. */
function topLevel(base) {
  const { env: _env, routes: _routes, workers_dev: _workersDev, ...rest } = structuredClone(base);
  return rest;
}

function address(origins, host) {
  if (origins.mode === 'domain') {
    return { routes: [{ pattern: host, custom_domain: true }], workers_dev: false };
  }
  return { workers_dev: true };
}

/** The queue names the base API config produces to and consumes from, in order. */
export function queueNames(apiBase) {
  const names = [];
  const add = (name) => {
    if (typeof name === 'string' && name !== '' && !names.includes(name)) names.push(name);
  };
  for (const p of apiBase.queues?.producers ?? []) add(p.queue);
  for (const c of apiBase.queues?.consumers ?? []) {
    add(c.queue);
    add(c.dead_letter_queue);
  }
  return names;
}

/**
 * The API Worker's self-host config.
 * @param {object} base      parsed apps/api/wrangler.jsonc
 * @param {object} values    saved settings (.env.selfhost)
 * @param {string} hyperdriveId
 */
export function buildApiConfig(base, values, hyperdriveId) {
  const origins = originsOf(values);
  const connectors = connectorsOf(values);
  if (connectors.length === 0) throw new SetupError('CONNECTORS is not set (telnyx, plivo).');
  if (!hyperdriveId) throw new SetupError('No Hyperdrive config id.');

  const vars = {
    APP_ENV: 'production',
    PROVIDER: 'connectors',
    CONNECTORS: connectors.join(','),
    KNOQRA_EDITION: EDITION,
    API_PUBLIC_ORIGIN: origins.api,
  };
  if (values.AI_PROVIDER) vars.AI_PROVIDER = values.AI_PROVIDER;
  if (values.AI_PROVIDER === 'openai') {
    if (values.AI_MODEL) vars.AI_MODEL = values.AI_MODEL;
    if (values.AI_BASE_URL) vars.AI_BASE_URL = values.AI_BASE_URL;
  }

  const hyperdrive = (base.hyperdrive?.length ? base.hyperdrive : [{ binding: 'HYPERDRIVE' }]).map(
    ({ localConnectionString: _local, ...binding }) => ({ ...binding, id: hyperdriveId }),
  );

  return {
    ...topLevel(base),
    name: API_WORKER,
    vars,
    hyperdrive,
    ratelimits: structuredClone(RATE_LIMITS),
    ...address(origins, new URL(origins.api).host),
  };
}

/**
 * The web Worker's (the Desk's) self-host config.
 * @param {object} base      parsed apps/web/wrangler.jsonc
 * @param {object} values    saved settings (.env.selfhost)
 */
export function buildWebConfig(base, values) {
  const origins = originsOf(values);
  const rest = topLevel(base);
  const services = (rest.services ?? []).filter((s) => s.binding !== 'API');
  return {
    ...rest,
    name: WEB_WORKER,
    vars: { APP_ENV: 'production' },
    services: [{ binding: 'API', service: API_WORKER }, ...services],
    ...address(origins, new URL(origins.desk).host),
  };
}

/** The text of a generated config file. */
export function renderConfig(config) {
  return `${CONFIG_HEADER}${JSON.stringify(config, null, 2)}\n`;
}
